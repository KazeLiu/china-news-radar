// Isolated SQLite checks for admin persistence, filtering, and secret redaction.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const server = path.resolve(__dirname, '../server');
const work = fs.mkdtempSync(path.join(os.tmpdir(), 'radar-admin-check-'));
const filename = path.join(work, 'admin.db');
fs.writeFileSync(filename, '');
const databaseUrl = `file:${filename.replaceAll('\\', '/')}`;
const prismaCli = path.join(path.dirname(require.resolve('prisma/package.json', { paths: [server] })), 'build/index.js');
const push = spawnSync(process.execPath, [prismaCli, 'db', 'push', '--skip-generate'], { cwd: server, env: { ...process.env, DATABASE_URL: databaseUrl }, encoding: 'utf8' });
if (push.status !== 0) throw new Error(`Isolated schema setup failed: ${push.stderr || push.stdout}`);
process.env.COLLECTOR_ENABLED = 'false';
process.env.AI_ANALYSIS_ENABLED = 'false';
process.env.OPENAI_API_KEY = '';
const { PrismaClient } = require(require.resolve('@prisma/client', { paths: [server] }));
const { NewsService } = require(path.join(server, 'dist/news/news.service.js'));
const { analysisKey } = require(path.join(server, 'dist/news/analysis.js'));
const { defaultConfig } = require(path.join(server, 'dist/news/admin-config.js'));
const db = new PrismaClient({ datasources: { db: { url: databaseUrl } } });
let service; let restarted;
(async () => {
  try {
    await db.newsSource.create({ data: { id: 'ap' } });
    const time = new Date(Date.now() - 60_000);
    const common = { sourceId: 'ap', originalPublisher: 'Associated Press', originalUrl: null, author: null, topic: 'policy', eventKey: 'fixture', contentHash: 'fixture', publishedAt: time, firstSeenAt: time, updatedAt: time, saved: true, visible: true };
    const hub = await db.newsItem.create({ data: { ...common, title: 'Beijing - AP News', summary: 'Beijing AP News', url: 'https://news.google.com/rss/articles/hub' } });
    const article = await db.newsItem.create({ data: { ...common, title: 'Beijing bans imports - AP News', summary: 'New policy', url: 'https://apnews.com/article/beijing-bans-imports' } });
    const key = analysisKey(article);
    const result = { version: 1, relation: 'related', topics: ['policy'], type: 'report', language: 'en', reason: '模拟政策快讯', translation: { title: '北京公布进口禁令', summary: '新政策' } };
    await db.newsAnalysis.create({ data: { key, inputJson: '{}', resultJson: JSON.stringify(result), status: 'done', analyzedAt: time } });
    await db.newsItem.update({ where: { id: article.id }, data: { analysisKey: key, aiStatus: 'done', updatedAt: time } });
    service = new NewsService(db); await service.onModuleInit();
    const hidden = await db.newsItem.findUnique({ where: { id: hub.id } });
    assert.equal(hidden.visible, false); assert.equal(hidden.aiStatus, 'excluded');
    assert.equal(hidden.saved, true); assert.equal(hidden.updatedAt.getTime(), time.getTime()); assert.equal(hidden.firstSeenAt.getTime(), time.getTime());
    assert.equal((await service.items({})).total, 1);
    const initial = await service.adminConfig();
    assert.equal(initial.ai.keyConfigured, false); assert.equal(Object.hasOwn(initial.ai, 'apiKey'), false);
    const secret = 'test-only-not-a-provider-key';
    await service.configureAi({ ...initial.ai, apiKey: secret, model: 'mock-model', dailyLimit: 7, instructions: '优先政策快讯' });
    assert.equal((await service.adminConfig()).ai.keyConfigured, true);
    assert.equal(JSON.stringify(await service.adminConfig()).includes(secret), false);
    await service.configureAi({ ...(await service.adminConfig()).ai, apiKey: '' });
    const custom = { id: 'custom-foreign', name: '自定义媒体', englishName: 'Fixture Press', kind: 'rss', website: 'https://foreign.example.org/', feedUrl: 'https://foreign.example.org/rss', publisherHosts: ['foreign.example.org'], description: '测试', pollSeconds: 90 };
    custom.feedUrls = [custom.feedUrl, 'https://backup.example.org/rss'];
    await service.configureSource(custom);
    assert.equal((await db.newsSource.findUnique({ where: { id: custom.id } })).enabled, false);
    await service.enableSource(custom.id, true);
    const deny = { id: 'deny-imports', sourceId: 'ap', field: 'titleContains', value: 'bans imports', enabled: true };
    const beforeJobs = await db.newsAnalysis.count();
    const updated = await service.configureRules([...initial.rules, deny]); assert.equal(updated.changed, 1);
    const excluded = await db.newsItem.findUnique({ where: { id: article.id } });
    assert.equal(excluded.visible, false); assert.equal(excluded.analysisKey, null); assert.equal(excluded.saved, true); assert.equal(excluded.updatedAt.getTime(), time.getTime());
    const preview = await service.previewRules({ title: article.title, summary: article.summary, url: article.url, sourceId: 'ap', rules: [deny] });
    assert.equal(preview.excluded, true);
    await service.configureRules(initial.rules);
    const restored = await db.newsItem.findUnique({ where: { id: article.id } });
    assert.equal(restored.visible, true); assert.equal(restored.titleZh, result.translation.title); assert.equal(restored.analysisKey, key); assert.equal(restored.saved, true); assert.equal(restored.updatedAt.getTime(), time.getTime());
    assert.equal(await db.newsAnalysis.count(), beforeJobs);
    service.onModuleDestroy();
    restarted = new NewsService(db); await restarted.onModuleInit();
    const config = await restarted.adminConfig();
    assert.equal(config.ai.model, 'mock-model'); assert.equal(config.ai.dailyLimit, 7); assert.equal(config.ai.keyConfigured, true);
    assert.equal(config.sources.find(s => s.id === custom.id).feedUrl, custom.feedUrl); assert.equal(config.sources.find(s => s.id === custom.id).state.enabled, true);
    assert.equal(JSON.stringify(config).includes(secret), false); assert.equal(await db.newsAnalysis.count(), beforeJobs);
    assert.equal((await restarted.sources()).find(s => s.id === custom.id).feedUrl, undefined);
    assert.deepEqual(config.sources.find(s => s.id === custom.id).feedUrls, custom.feedUrls);
    await restarted.configureRules([...initial.rules, { id: 'deleted-source-rule', sourceId: 'ap', field: 'titleContains', value: 'podcast', enabled: true }]);
    const beforeDelete = await db.newsItem.count();
    await restarted.deleteSource('ap');
    assert.equal((await db.newsSource.findUnique({ where: { id: 'ap' } })).enabled, false);
    assert.equal(await db.newsItem.count(), beforeDelete);
    assert.equal((await db.newsItem.findUnique({ where: { id: article.id } })).saved, true);
    await restarted.configureAi({ ...config.ai, clearKey: true });
    restarted.onModuleDestroy();
    const last = new NewsService(db); await last.onModuleInit();
    const finalConfig = await last.adminConfig();
    assert.equal(finalConfig.ai.keyConfigured, false);
    assert.equal(finalConfig.sources.some(s => s.id === 'ap'), false);
    assert.equal(finalConfig.rules.some(r => r.id === 'deleted-source-rule' && r.sourceId === 'ap'), true);
    assert.equal((await db.newsItem.findUnique({ where: { id: article.id } })).firstSeenAt.getTime(), time.getTime());
    last.onModuleDestroy();
    console.log(JSON.stringify({ ok: true, externalCalls: 0, checks: ['startup hides stored hub', 'normal short report retained', 'bookmark/timestamps preserved', 'ordered RSS addresses persist', 'deleted source remains absent after restart', 'deleted source retains bookmarks and scoped rules', 'source and AI persistence', 'secret redaction and clear', 'preview', 'rule removal restores cache without new calls'] }));
  } finally {
    service?.onModuleDestroy(); restarted?.onModuleDestroy(); await db.$disconnect();
    for (const suffix of ['', '-journal', '-wal', '-shm']) {
      const target = `${filename}${suffix}`;
      if (path.dirname(target) !== work) throw new Error('Unexpected test path');
      if (fs.existsSync(target)) fs.unlinkSync(target);
    }
    fs.rmdirSync(work);
  }
})().catch(error => { console.error(error.message); process.exitCode = 1; });
